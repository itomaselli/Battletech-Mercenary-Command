def build():
 units=json.loads((ROOT/'data/units.json').read_text())
 refs=json.loads((ROOT/'docs/unit-art-references.json').read_text())
 by_chassis={r['chassis']:r for r in refs}
 result={}
 for unit in units:
  note,primary,detail,source=BASES[unit['chassis']]
  lines=textwrap.dedent(source).strip('\n').splitlines()
  assert len(lines)<=24,(unit['chassis'],len(lines))
  for line in lines:assert len(line)==16 and set(line)<=set('.#+'),(unit['chassis'],len(line),line)
  rows=[list(line) for line in lines]
  variant_note='Configuración base del chasis.'
  if unit['id'] in PATCHES:
   variant_note,patches=PATCHES[unit['id']]
   for x,y,patch in patches:
    assert 0<=x and x+len(patch)<=16 and 0<=y<len(rows)
    rows[y][x:x+len(patch)]=list(patch)
  # Ground vehicles retain a low silhouette. Mechs stand on the same baseline.
  top=1 if unit['kind']=='vehicle' else 23-len(rows)
  lines=['.'*16]*top+[''.join(row) for row in rows]
  lines+=['.'*16]*(24-len(lines))
  assert len(lines)==24
  reference=by_chassis[unit['chassis']]
  result[unit['id']]={'chassis':unit['chassis'],'palette':[primary,detail],'rows':lines,'design':note,'variant_detail':variant_note,'reference':reference['page']}
 assert len(result)==56
 assert len({tuple(v['rows']) for v in result.values()})==56,'Every catalog entry must differ geometrically, not just by color'
 (ROOT/'visual/unit_sprites.json').write_text(json.dumps({'version':1,'width':16,'height':24,'units':result},ensure_ascii=False,indent=2)+'\n')
 print('Compiled 56 unique native pixel masks / 32 chassis')
if __name__=='__main__':build()
